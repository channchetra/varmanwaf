/// A security event generated by the WAF engine.
///
/// Sent to the control plane for analysis and dashboard display.
#[derive(Debug, Clone)]
pub struct SecurityEvent {
    pub site_id: String,
    pub request_id: String,
    pub client_ip: String,
    pub method: String,
    pub scheme: String,
    pub protocol: String,
    pub host: String,
    pub path: String,
    pub query_string: String,
    pub rule_id: String,
    pub rule_name: String,
    pub action: String,
    pub score: u32,
    pub details: String,
    /// Status code actually returned to the client for this event
    /// (403 for block, 503 for challenge, 0 when the request continues).
    pub response_status: u32,
    pub user_agent: String,
    pub country_code: String,
    pub matched_tags: Vec<String>,
}

/// An access log entry for a proxied request.
///
/// Batched and shipped to the control plane for analytics.
#[derive(Debug, Clone)]
pub struct AccessLogEntry {
    pub site_id: String,
    pub request_id: String,
    pub client_ip: String,
    pub method: String,
    pub scheme: String,
    pub host: String,
    pub path: String,
    pub query_string: String,
    pub protocol: String,
    pub status_code: u32,
    pub response_size: u64,
    pub upstream_addr: String,
    pub upstream_latency_ms: u64,
    pub total_latency_ms: u64,
    pub cache_status: String,
    pub user_agent: String,
    pub referer: String,
    pub tls_version: String,
    pub country_code: String,
    pub request_headers: Vec<(String, String)>,
    pub request_body: Option<Vec<u8>>,
    pub request_body_size: u64,
    pub request_body_truncated: bool,
    /// Response header snapshot, capped like the request one.
    pub response_headers: Vec<(String, String)>,
    /// Prefix of the response body kept for the log; `None` when it was not
    /// captured (binary payload, compressed, or capture disabled).
    pub response_body: Option<Vec<u8>>,
    /// Full response body size as counted while streaming, kept or not.
    pub response_body_size: u64,
    pub response_body_truncated: bool,
}

